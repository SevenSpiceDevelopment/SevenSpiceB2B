// Helper translation functions
export function t(key, locale) {
  const currentLocale = locale === "ur" ? "ur" : "en";
  return translations[currentLocale][key] || translations["en"][key] || key;
}

export function translateProduct(product, locale) {
  if (locale !== "ur") return product;
  const mapped = productTranslationsUr[product.name];
  if (mapped) {
    return {
      ...product,
      name: mapped.name,
      description: mapped.description,
      category: mapped.category,
      packaging_info: mapped.packaging_info,
      price_moq: mapped.price_moq
    };
  }
  return product;
}

export function translateProducts(products, locale) {
  if (!products) return [];
  return products.map(p => translateProduct(p, locale));
}

export function translateBlogPost(post, locale) {
  if (locale !== "ur") return post;
  const mapped = blogTranslationsUr[post.title];
  if (mapped) {
    return {
      ...post,
      title: mapped.title,
      content: mapped.content,
      category: mapped.category,
      author: mapped.author
    };
  }
  return post;
}

export function translateBlogPosts(posts, locale) {
  if (!posts) return [];
  return posts.map(b => translateBlogPost(b, locale));
}
